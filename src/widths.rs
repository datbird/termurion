pub fn is_full_width(c: u32, version: u8) -> bool {
    in_ranges(c, if version >= 9 { FULL9 } else { FULL8 })
}

/// `iTermIsAmbiguousWidthCharacter`.
pub fn is_ambiguous(c: u32, version: u8) -> bool {
    in_ranges(c, if version >= 9 { AMB9 } else { AMB8 })
}

/// `iTermIsFlagCharacter`: regional indicators and the black flag, from version 9.
pub fn is_flag(c: u32, version: u8) -> bool {
    version >= 9 && ((0x1F1E6..=0x1F1FF).contains(&c) || c == 0x1F3F4)
}

/// `iTermIsDoubleWidthCharacter`.
pub fn is_double_width(c: u32, ambiguous_wide: bool, version: u8, full_width_flags: bool) -> bool {
    // iTerm2's fast path for ASCII, Latin-1 and the long run below Hangul Jamo.
    if c <= 0xa0 || (c > 0x452 && c < 0x1100) {
        return false;
    }
    is_full_width(c, version) || (ambiguous_wide && is_ambiguous(c, version)) || (full_width_flags && is_flag(c, version))
}

/// `iTermIsEmojiAcceptingVS16`: a character VS16 makes an emoji with two cells.
pub fn accepts_vs16(c: u32) -> bool {
    in_ranges(c, VS16)
}

/// A regional indicator symbol (U+1F1E6 to U+1F1FF).
pub fn is_regional_indicator(c: u32) -> bool {
    (0x1F1E6..=0x1F1FF).contains(&c)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_follow_iterm2() {
        assert!(is_double_width(0x4E00, false, 8, true));
        assert!(!is_double_width(0x1F600, false, 8, true), "emoji were narrow in 8");
        assert!(is_double_width(0x1F600, false, 9, true), "and became wide in 9");
        assert!(!is_double_width(0x00A7, false, 9, true));
        assert!(is_double_width(0x00A7, true, 9, true), "ambiguous");
        assert!(is_double_width(0x1F1E6, false, 9, true));
        assert!(!is_double_width(0x1F1E6, false, 9, false));
        assert!(!is_double_width(0x1F1E6, false, 8, true), "flags need 9");
        assert!(!is_double_width(0x41, true, 9, true));
        assert!(accepts_vs16(0x2764));
        assert!(!accepts_vs16(0x41));
        assert!(is_regional_indicator(0x1F1FA) && !is_regional_indicator(0x1F200));
        assert!(is_flag(0x1F3F4, 9) && !is_flag(0x1F3F4, 8));
    }

    #[test]
    fn tables_are_sorted_and_disjoint() {
        for t in [FULL8, FULL9, AMB8, AMB9, VS16] {
            assert!(t.iter().all(|&(a, b)| a <= b));
            assert!(t.windows(2).all(|w| w[0].1 < w[1].0));
        }
    }
}
