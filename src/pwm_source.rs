//! The password manager's sources (pure): the `Source` trait every backing store implements,
//! the source kinds with their stored names and menu titles, what each source can do (`Caps`),
//! and the Windows Credential Manager naming that round-trips iTerm2's keychain keys. The Win32
//! side of Credential Manager is `pwm_credman.rs`; the CLI and adapter sources come in later
//! tasks. A source runs on the password manager's worker thread, never the UI thread.

use crate::pwm::{Account, Secret, SEP};

/// The globals key that holds the chosen source's stored name (iTerm2's
/// `NoSyncPasswordManagerDataSourceName`, so an imported iTerm2 setting carries over).
pub const SOURCE_KEY: &str = "NoSyncPasswordManagerDataSourceName";

/// Credential Manager targets are `SERVICE/<account><SEP><user>` (iTerm2's keychain service is
/// "iTerm2", its items keyed by `account + SEP + user`).
pub const SERVICE: &str = "Tandem";

/// The password manager's sources, in the gear menu's order.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    CredentialManager,
    OnePassword,
    LastPass,
    KeePassXC,
    Bitwarden,
    Keeper,
}

impl Kind {
    pub const ALL: [Kind; 6] = [
        Kind::CredentialManager,
        Kind::OnePassword,
        Kind::LastPass,
        Kind::KeePassXC,
        Kind::Bitwarden,
        Kind::Keeper,
    ];

    /// The name stored under `SOURCE_KEY` (`PasswordManagerDataSourceProvider.DataSource`).
    /// Credential Manager keeps iTerm2's "Keychain" so iTerm2-shaped settings import unchanged.
    pub fn stored(self) -> &'static str {
        match self {
            Kind::CredentialManager => "Keychain",
            Kind::OnePassword => "OnePassword",
            Kind::LastPass => "LastPass",
            Kind::KeePassXC => "KeePassXC",
            Kind::Bitwarden => "Bitwarden",
            Kind::Keeper => "Keeper",
        }
    }

    /// The kind for a stored name; anything unknown is the default, Credential Manager
    /// (iTerm2's `DataSource(rawValue:) ?? .defaultValue`).
    pub fn from_stored(s: &str) -> Kind {
        Kind::ALL.into_iter().find(|k| k.stored() == s).unwrap_or(Kind::CredentialManager)
    }

    /// The gear menu item's title (`iTermPasswordManager.xib`, "macOS Keychain" in Windows words).
    pub fn menu_title(self) -> &'static str {
        match self {
            Kind::CredentialManager => "Windows Credential Manager",
            Kind::OnePassword => "1Password Integration",
            Kind::LastPass => "LastPass Integration",
            Kind::KeePassXC => "KeePassXC Integration",
            Kind::Bitwarden => "Bitwarden Integration",
            Kind::Keeper => "Keeper Security",
        }
    }
}

/// An Add Account checkbox a source declares (the adapter protocol's `AddAccountToggle`).
/// `Deserialize` with the protocol's camelCase names so `pwm_adapter`'s `HandshakeResponse`
/// decodes straight into it, with no separate wire type to keep in step (Task 5 decision).
#[derive(Clone, Debug, PartialEq, Eq, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Toggle {
    pub key: String,
    pub label: String,
    pub note: Option<String>,
    pub default_value: bool,
}

/// A field in a source's Settings sheet (the adapter protocol's `SettingsField`). `Deserialize`
/// for the same reason as `Toggle` (Task 5 decision).
#[derive(Clone, Debug, PartialEq, Eq, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Field {
    pub key: String,
    pub label: String,
    pub placeholder: Option<String>,
    pub is_secret: bool,
    pub note: Option<String>,
    /// iTerm2 keeps such a value in the keychain; Tandem keeps it in memory for the run only.
    pub persist_in_keychain: bool,
}

/// What a source can do (`PasswordManagerDataSource`'s capability properties).
#[derive(Clone, Debug, Default)]
pub struct Caps {
    /// `supportsInPlaceEdit`: a rename edits the record instead of delete-then-add.
    pub in_place: bool,
    /// `canEditPassword`: the Edit panel's password field is enabled.
    pub can_edit_password: bool,
    /// `requiresPasswordForAdd`: Add refuses an empty password.
    pub requires_password: bool,
    /// `autogeneratedPasswordsOnly`: Add shows "Autogenerated" and takes no password.
    pub generated_only: bool,
    /// `supportsMultipleAccounts`: Switch Account is enabled.
    pub multiple_accounts: bool,
    /// `canResetConfiguration`: the Reset item is enabled and names the source.
    pub can_reset: bool,
    /// The first Add Account toggle, when the source declares any.
    pub add_toggle: Option<Toggle>,
    /// The Settings sheet's fields (none means no "Settings\u{2026}" item).
    pub settings: Vec<Field>,
    /// Custom commands as (name, label), shown in the gear menu after Switch Account.
    pub commands: Vec<(String, String)>,
}

/// A backing store for the password manager. Every call may block (a CLI, a Win32 call), so
/// only the password manager's worker thread calls it. Errors are the store's own message; the
/// window wraps them in iTerm2's alert texts (for a failed read, `password_failed`).
pub trait Source: Send {
    fn kind(&self) -> Kind;
    fn name(&self) -> String;
    fn caps(&self) -> Caps;
    /// `checkAvailability`: Ok when the source can be used now, else the reason.
    fn available(&mut self) -> Result<(), String>;
    /// Every account, unsorted (the window sorts by display string).
    fn accounts(&mut self) -> Result<Vec<Account>, String>;
    /// The password and, for a source with one-time codes, the current code.
    fn password(&mut self, a: &Account) -> Result<(Secret, Option<Secret>), String>;
    fn set_password(&mut self, a: &Account, p: Secret) -> Result<(), String>;
    fn delete(&mut self, a: &Account) -> Result<(), String>;
    /// Adds an account; `flags` are the Add Account toggle states as (key, on).
    fn add(&mut self, name: &str, user: &str, p: Secret, flags: &[(String, bool)]) -> Result<Account, String>;
    /// Only called when `caps().in_place`; `None` leaves a field unchanged.
    fn edit_in_place(&mut self, a: &Account, name: Option<&str>, user: Option<&str>, p: Option<Secret>) -> Result<(), String>;
    fn toggle_otp(&mut self, a: &Account) -> Result<Account, String>;
    /// Drops any cached account list so the next `accounts` fetches afresh.
    fn reload(&mut self);
    fn reset_configuration(&mut self);
    fn switch_account(&mut self) -> Result<(), String>;
    /// A warning the last account list came with (an adapter's `ListAccountsResponse.warning`),
    /// taken once; the window shows it as iTerm2 does (`AP:690-699`).
    fn take_warning(&mut self) -> Option<String> {
        None
    }
    /// An adapter's custom command from the gear menu (`runCustomCommand:`): its message, if
    /// any. Only an adapter declares commands.
    fn custom_command(&mut self, _name: &str) -> Result<Option<String>, String> {
        Err("This password manager has no commands.".to_string())
    }
}

/// Windows Credential Manager's capabilities (`KeychainPasswordDataSource`): no in-place edit
/// (a rename is delete-then-add), the password can be changed, Add takes an empty password,
/// one account, nothing to reset, no toggles, settings or commands.
pub fn credman_caps() -> Caps {
    Caps { can_edit_password: true, ..Caps::default() }
}

/// The alert text for a failed password read (`W:1948-1957`, "Keychain" in Windows words). The
/// window shows it for every source, as iTerm2 does.
pub fn password_failed(message: &str) -> String {
    format!("Could not get password. Credential Manager query failed: {message}")
}

/// The Credential Manager target for an account: `Tandem/<account><SEP><user>`. iTerm2's
/// modern add always joins with the separator, so an empty user leaves it trailing.
pub fn target_name(account: &str, user: &str) -> String {
    format!("{SERVICE}/{account}{SEP}{user}")
}

/// The account a Credential Manager target names, or `None` when it is not one of Tandem's.
/// The part after `Tandem/` splits at the first separator into account and user; with no
/// separator it is iTerm2's one-part legacy item, the whole part the account and the user
/// empty. The display string is that part unchanged (iTerm2's `displayString`, the keychain
/// account name) and the id is the whole target.
pub fn parse_target(target: &str) -> Option<Account> {
    let combined = target.strip_prefix(SERVICE)?.strip_prefix('/')?;
    let (account, user) = combined.split_once(SEP).unwrap_or((combined, ""));
    Some(Account {
        id: target.to_string(),
        account_name: account.to_string(),
        user_name: user.to_string(),
        display: combined.to_string(),
        has_otp: false,
        send_otp: false,
        source_label: None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn credman_names_follow_iterm2() {
        let t = target_name("github", "me");
        assert_eq!(t, "Tandem/github\u{2002}\u{2014}\u{2002}me");
        let a = parse_target(&t).expect("a Tandem target");
        assert_eq!(a.account_name, "github");
        assert_eq!(a.user_name, "me");
        assert_eq!(a.display, "github\u{2002}\u{2014}\u{2002}me");
        assert_eq!(a.id, t);
        assert!(!a.has_otp && !a.send_otp && a.source_label.is_none());

        // iTerm2's one-part legacy item: the whole name is the account, the user is empty.
        let solo = parse_target("Tandem/solo").expect("a Tandem target");
        assert_eq!(solo.account_name, "solo");
        assert_eq!(solo.user_name, "");
        assert_eq!(solo.display, "solo");
        assert_eq!(solo.id, "Tandem/solo");

        assert!(parse_target("Other/x").is_none());
        assert!(parse_target("Tandemx/y").is_none());

        // iTerm2's modern add with no user keeps the separator; it round-trips to an empty user.
        let no_user = target_name("a", "");
        assert!(no_user.ends_with(SEP));
        let a = parse_target(&no_user).expect("a Tandem target");
        assert_eq!((a.account_name.as_str(), a.user_name.as_str()), ("a", ""));
        assert_eq!(a.display, format!("a{SEP}"));

        // The first separator splits, as iTerm2's range(of:).
        let two = parse_target(&format!("Tandem/x{SEP}y{SEP}z")).expect("a Tandem target");
        assert_eq!((two.account_name.as_str(), two.user_name.as_str()), ("x", &*format!("y{SEP}z")));

        assert_eq!(Kind::from_stored("Keychain"), Kind::CredentialManager);
        assert_eq!(Kind::from_stored("Bogus"), Kind::CredentialManager);
        for k in Kind::ALL {
            assert_eq!(Kind::from_stored(k.stored()), k);
        }
        assert_eq!(Kind::OnePassword.stored(), "OnePassword");
        assert_eq!(Kind::CredentialManager.menu_title(), "Windows Credential Manager");
        assert_eq!(Kind::Keeper.menu_title(), "Keeper Security");
        assert_eq!(SOURCE_KEY, "NoSyncPasswordManagerDataSourceName");

        let c = credman_caps();
        assert!(!c.in_place);
        assert!(c.can_edit_password);
        assert!(!c.requires_password);
        assert!(!c.generated_only && !c.multiple_accounts && !c.can_reset);
        assert!(c.add_toggle.is_none() && c.settings.is_empty() && c.commands.is_empty());

        assert_eq!(password_failed("Element not found."), "Could not get password. Credential Manager query failed: Element not found.");
    }
}
