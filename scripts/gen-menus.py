#!/usr/bin/env python3
"""Builds schema/menus.toml from iTerm2's MainMenu.xib (read-only reference clone).

Each menu item keeps iTerm2's title, its action selector (Tandem's command id), its
XIB identifier (what the Python API's MenuItem request names), and its key equivalent
and modifier mask. Usage: scripts/gen-menus.py [path/to/iTerm2]
"""
import base64
import sys
import xml.etree.ElementTree as ET

ref = sys.argv[1] if len(sys.argv) > 1 else "/home/tbird/gitrepos/iterm2-ref"
root = ET.parse(f"{ref}/sources/MainMenu/Base.lproj/MainMenu.xib").getroot()
main = [m for m in root.iter("menu") if m.get("systemMenu") == "main"][0]
out = ["# Generated by scripts/gen-menus.py from iTerm2's MainMenu.xib. Do not edit by hand.", ""]


# Two quoting helpers. q keeps the existing key lines (paths, selectors, keys, mods) as they
# were: characters outside ASCII stay raw, only control characters are escaped. qa is for
# identifiers, which the Python API compares byte for byte: every character outside ASCII is
# escaped, so the file keeps an identifier's exact code points (an ellipsis, a NBSP).
def q(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    # Control characters (a base64 key's CR) as TOML escapes; TOML refuses them raw.
    s = "".join({"\r": "\\r", "\t": "\\t", "\n": "\\n"}.get(c, f"\\u{ord(c):04X}") if ord(c) < 0x20 or ord(c) == 0x7F else c for c in s)
    return '"' + s + '"'


def qa(s):
    """q with every character outside ASCII written as a TOML escape."""

    def one(c):
        if c in '\\"':
            return "\\" + c
        if ord(c) < 0x80:
            return c
        return f"\\u{ord(c):04X}" if ord(c) < 0x10000 else f"\\U{ord(c):08X}"

    return '"' + "".join(one(c) for c in s) + '"'


def walk(menu, path):
    for it in menu.findall("items/menuItem"):
        if it.get("isSeparatorItem") == "YES":
            out.append("[[item]]")
            out.append(f"path = [{', '.join(q(p) for p in path)}]")
            out.append("separator = true")
            out.append("")
            continue
        title = it.get("title", "").replace("…", "...")
        key = it.get("keyEquivalent", "")
        mm = it.find("modifierMask")
        # A key the XIB cannot write as an attribute (Enter, Esc) is a base64 child element.
        # One with no modifier is skipped: Tandem's menus never disable by state, so a bare
        # Esc chord would take Esc from every shell (iTerm2's Zoom Out has it only while zoomed).
        b64 = it.find("string[@key='keyEquivalent']")
        if not key and b64 is not None and b64.get("base64-UTF8") == "YES":
            text = "".join((b64.text or "").split())
            key = base64.b64decode(text + "=" * (-len(text) % 4)).decode("utf-8")
            if mm is not None and not any(mm.get(m) == "YES" for m in ("control", "option", "shift", "command")):
                key = ""
        mods = []
        if key:
            if mm is None:
                mods = ["cmd"]
            else:
                names = {"control": "ctrl", "option": "opt", "shift": "shift", "command": "cmd"}
                mods = [names[m] for m in ("control", "option", "shift", "command") if mm.get(m) == "YES"]
            if len(key) == 1 and key.isalpha() and key.isupper():
                key = key.lower()
                if "shift" not in mods:
                    mods.append("shift")
        act = it.find("connections/action")
        sel = act.get("selector") if act is not None else ""
        sub = it.find("menu")
        out.append("[[item]]")
        out.append(f"path = [{', '.join(q(p) for p in path + [title])}]")
        out.append(f"selector = {q(sel)}")
        if it.get("identifier"):
            out.append(f"identifier = {qa(it.get('identifier'))}")
        if key:
            out.append(f"key = {q(key)}")
            out.append(f"mods = [{', '.join(q(m) for m in mods)}]")
        if sub is not None:
            out.append("submenu = true")
        if it.get("alternate") == "YES":
            out.append("alternate = true")
        out.append("")
        if sub is not None:
            walk(sub, path + [title])


walk(main, [])
open("schema/menus.toml", "w").write("\n".join(out))
print(sum(1 for l in out if l == "[[item]]"), "items")
