#!/usr/bin/env python3
"""Builds schema/keymaps.toml from iTerm2's plists (read-only reference clone).

It holds the factory global key map, the default pointer bindings, and the three
key mapping presets. Usage: scripts/gen-keymaps.py [path/to/iTerm2]
"""
import plistlib
import sys

ref = sys.argv[1] if len(sys.argv) > 1 else "/home/tbird/gitrepos/iterm2-ref"


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


def val(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return q(v)
    raise SystemExit(f"unexpected value {v!r}")


def tables(out, prefix, d):
    for key in sorted(d):
        out.append(f"[{prefix}.{q(key)}]")
        for field in sorted(d[key]):
            out.append(f"{q(field)} = {val(d[key][field])}")
        out.append("")


def load(name):
    with open(f"{ref}/plists/{name}", "rb") as f:
        return plistlib.load(f)


out = ["# Generated by scripts/gen-keymaps.py from iTerm2's plists. Do not edit by hand.", ""]
tables(out, "global", load("DefaultGlobalKeyMap.plist"))
tables(out, "pointer", load("DefaultPointerActions.plist"))
presets = load("PresetKeyMappings.plist")
for name in sorted(presets):
    tables(out, f"preset.{q(name)}", presets[name])
open("schema/keymaps.toml", "w").write("\n".join(out))
print(sum(1 for l in out if l.startswith("[")), "tables")
