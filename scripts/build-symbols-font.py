#!/usr/bin/env python3
"""Builds resources/fonts/TermurionSymbols.ttf: a DejaVu Sans subset (license unchanged, see
resources/fonts/LICENSE-DejaVu) with stand-ins for the Segoe icon code points Termurion draws,
for systems without Segoe (macOS, Linux).

Usage: scripts/build-symbols-font.py /path/to/DejaVuSans.ttf   (needs fontTools)
The table below is the whole font: add a code point here and run it again.
"""
import sys
from fontTools import subset
from fontTools.ttLib import TTFont

OUT = "resources/fonts/TermurionSymbols.ttf"

# Shapes the egui windows draw as themselves.
PLAIN = [
    0x2B, 0x3C, 0x3E, 0x3F, 0x2022, 0x2139, 0x2190, 0x2191, 0x2192, 0x2193, 0x2197, 0x21BB, 0x21C5,
    0x21E7, 0x21EA, 0x2212, 0x221E, 0x2261, 0x2295, 0x22EF, 0x2303, 0x2318, 0x2325, 0x232B, 0x2387,
    0x25A0, 0x25A3, 0x25A4, 0x25A6, 0x25AD, 0x25AE, 0x25AF, 0x25B4, 0x25B6, 0x25B8, 0x25BE, 0x25C9,
    0x25CB, 0x25CE, 0x25CF, 0x25D1, 0x25D4, 0x2605, 0x2606, 0x262F, 0x2630, 0x263A, 0x263E, 0x266A,
    0x2699, 0x26A0, 0x26A1, 0x2709, 0x270E, 0x2713, 0x2714, 0x2715, 0x2750, 0x276E, 0x276F, 0x27A1,
    0x27A4, 0x27F5, 0x27F6, 0x25A1, 0x2691, 0x21F6,
]

# Segoe MDL2 / Fluent code point -> the DejaVu character that stands in for it.
SEGOE = {
    0xE700: 0x2630, 0xE701: 0x25C9, 0xE708: 0x263E, 0xE70D: 0x25BE, 0xE70E: 0x25B4, 0xE70F: 0x270E,
    0xE710: 0x2B, 0xE711: 0x2715, 0xE712: 0x22EF, 0xE713: 0x2699, 0xE716: 0x2630, 0xE718: 0x2605,
    0xE71A: 0x25A0, 0xE71B: 0x2197, 0xE71E: 0x2715, 0xE721: 0x25CE, 0xE723: 0x25A4, 0xE724: 0x27A4,
    0xE72C: 0x21BB, 0xE72D: 0x21EA, 0xE72E: 0x25A3, 0xE734: 0x2606, 0xE737: 0x25AD, 0xE738: 0x2212,
    0xE73E: 0x2713, 0xE740: 0x25A1, 0xE74D: 0x232B, 0xE756: 0x276F, 0xE768: 0x25B6, 0xE76B: 0x276E,
    0xE76C: 0x276F, 0xE76E: 0x25B6, 0xE774: 0x2295, 0xE77B: 0x263A, 0xE77F: 0x25D1, 0xE7B8: 0x25A4,
    0xE7BA: 0x26A0, 0xE7C1: 0x26A1, 0xE7ED: 0x266A, 0xE7F4: 0x3E, 0xE823: 0x25D4, 0xE83E: 0x26A1,
    0xE83F: 0x25AE, 0xE890: 0x25C9, 0xE897: 0x3F, 0xE8A5: 0x25A4, 0xE8AB: 0x2387, 0xE8B3: 0x25A4,
    0xE8B7: 0x25B8, 0xE8BB: 0x2715, 0xE8BD: 0x2709, 0xE8C6: 0x25A4, 0xE8C8: 0x2750, 0xE8FD: 0x2261,
    0xE90F: 0x2699, 0xE91F: 0x25CB, 0xE921: 0x2212, 0xE922: 0x25A1, 0xE923: 0x2750, 0xE945: 0x2699,
    0xE946: 0x2139, 0xE950: 0x25A3, 0xE968: 0x21C5, 0xE996: 0x25AF, 0xE99A: 0x25CF, 0xEA3B: 0x25CF,
    0xEA8F: 0x21BB, 0xEBE8: 0x2691, 0xEC05: 0x21F6, 0xEEA0: 0x25A6,
}


def main(src):
    font = TTFont(src)
    opts = subset.Options()
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=sorted(set(PLAIN) | set(SEGOE.values())))
    sub.subset(font)
    for table in font["cmap"].tables:
        if table.isUnicode():
            for pua, base in SEGOE.items():
                table.cmap[pua] = table.cmap[base]
    for rec in font["name"].names:
        if rec.nameID in (1, 4, 16):
            rec.string = "TermurionSymbols"
        elif rec.nameID == 6:
            rec.string = "TermurionSymbols"
    font.save(OUT)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
