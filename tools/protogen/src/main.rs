// Generates src/api_pb.rs from proto/api.proto without protoc: protox parses the proto file
// into a FileDescriptorSet in pure Rust, then prost-build turns that into Rust source. Run from
// the repo root (scripts/xt does this) with:
//   cargo run --manifest-path tools/protogen/Cargo.toml
// The output is checked in; nothing about Tandem's own build depends on this crate.

use std::fs;
use std::path::Path;

fn main() {
    let proto_dir = Path::new("proto");
    let proto_file = proto_dir.join("api.proto");
    let fds = protox::compile([&proto_file], [proto_dir]).unwrap_or_else(|e| {
        panic!("failed to compile {}: {e}", proto_file.display());
    });

    let out_dir = std::env::temp_dir().join(format!("tandem-protogen-{}", std::process::id()));
    fs::create_dir_all(&out_dir).expect("create temporary output directory");

    prost_build::Config::new()
        .out_dir(&out_dir)
        .compile_fds(fds)
        .expect("generate Rust code from the descriptor set");

    let mut files = Vec::new();
    for entry in fs::read_dir(&out_dir).expect("read temporary output directory") {
        let entry = entry.expect("read directory entry");
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            files.push(path);
        }
    }
    // One proto package gives one file; anything else must fail loudly, never pick one.
    assert_eq!(files.len(), 1, "prost-build must emit exactly one .rs file, emitted {files:?}");
    let generated = files.remove(0);
    let code = fs::read_to_string(&generated).expect("read generated Rust file");
    fs::remove_dir_all(&out_dir).ok();

    let mut out = String::new();
    out.push_str("// @generated by tools/protogen from proto/api.proto; do not edit.\n");
    out.push_str(&code);

    let dest = Path::new("src").join("api_pb.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("write {}: {e}", dest.display()));
    println!("wrote {}", dest.display());
}
